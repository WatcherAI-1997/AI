#!/bin/bash
################################################################################
# 🏹 TamerlanAI - Автоматическая установка
# Автор: Джама Ваккасов (jamavakkasoff@gmail.com)
################################################################################

set -e  # Выход при ошибке

echo "================================================================================"
echo "🏹 TAMERLANAI - АВТОМАТИЧЕСКАЯ УСТАНОВКА"
echo "================================================================================"
echo "Автор: Джама Ваккасов (jamavakkasoff@gmail.com)"
echo ""

# Цвета для вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Функции для вывода
info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Переход в директорию проекта
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

info "Рабочая директория: $SCRIPT_DIR"
echo ""

# ============================================================================
# Шаг 1: Проверка Python
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📋 Шаг 1/6: Проверка Python"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if ! command -v python3 &> /dev/null; then
    error "Python 3 не найден. Установите Python 3.8+"
    exit 1
fi

PYTHON_VERSION=$(python3 --version | cut -d' ' -f2)
info "Python версия: $PYTHON_VERSION"
echo ""

# ============================================================================
# Шаг 2: Установка зависимостей
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📦 Шаг 2/6: Установка зависимостей"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

cd backend

info "Установка PyTorch (CPU версия)..."
pip install torch --index-url https://download.pytorch.org/whl/cpu --quiet

info "Установка FastAPI и зависимостей..."
pip install -q fastapi uvicorn pydantic pydantic-settings python-dotenv python-multipart requests

info "✅ Все зависимости установлены"
echo ""

# ============================================================================
# Шаг 3: Создание директорий
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📁 Шаг 3/6: Создание директорий"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

mkdir -p models
mkdir -p logs

info "✅ Директории созданы"
echo ""

# ============================================================================
# Шаг 4: Обучение модели
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🧠 Шаг 4/6: Обучение модели"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if [ -f "models/best_model.pt" ]; then
    warn "Модель уже обучена (models/best_model.pt существует)"
    read -p "Хотите переобучить? (y/N): " -n 1 -r
    echo
    if [[ $REPLY =~ ^[Yy]$ ]]; then
        info "Запуск обучения..."
        python3 train_demo.py
    else
        info "Пропускаем обучение"
    fi
else
    info "Модель не найдена. Запуск обучения..."
    python3 train_demo.py

    # Копирование модели в нужное место
    if [ -d "checkpoints" ]; then
        info "Копирование модели в models/..."
        cp checkpoints/best_model.pt models/
        cp checkpoints/tokenizer.json models/
    fi
fi

echo ""

# ============================================================================
# Шаг 5: Проверка модели
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✅ Шаг 5/6: Проверка модели"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if [ ! -f "models/best_model.pt" ]; then
    error "Модель не найдена: models/best_model.pt"
    exit 1
fi

if [ ! -f "models/tokenizer.json" ]; then
    error "Токенизатор не найден: models/tokenizer.json"
    exit 1
fi

MODEL_SIZE=$(du -h models/best_model.pt | cut -f1)
info "✅ Модель найдена: models/best_model.pt ($MODEL_SIZE)"
info "✅ Токенизатор найден: models/tokenizer.json"
echo ""

# ============================================================================
# Шаг 6: Создание запускающих скриптов
# ============================================================================
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🚀 Шаг 6/6: Создание запускающих скриптов"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

# Создание start.sh
cat > start.sh << 'STARTEOF'
#!/bin/bash
echo "🏹 Запуск TamerlanAI..."
cd "$(dirname "$0")"
python3 main.py
STARTEOF

chmod +x start.sh

# Создание test.sh
cat > test.sh << 'TESTEOF'
#!/bin/bash
echo "🧪 Тестирование TamerlanAI..."
cd "$(dirname "$0")"
python3 test_real.py
TESTEOF

chmod +x test.sh

info "✅ Скрипты созданы: start.sh, test.sh"
echo ""

# ============================================================================
# Завершение
# ============================================================================
echo "================================================================================"
echo "✅ УСТАНОВКА ЗАВЕРШЕНА!"
echo "================================================================================"
echo ""
echo "📊 Информация:"
echo "   - Модель: TamerlaneGPT (3.3M параметров)"
echo "   - Размер: $MODEL_SIZE"
echo "   - Языки: Казахский, Турецкий, Русский, Английский"
echo "   - Device: CPU"
echo ""
echo "🚀 Запуск сервера:"
echo "   cd backend"
echo "   ./start.sh"
echo "   или:"
echo "   python3 main.py"
echo ""
echo "🧪 Тестирование:"
echo "   cd backend"
echo "   ./test.sh"
echo "   или:"
echo "   python3 test_real.py"
echo ""
echo "📖 Документация API:"
echo "   http://localhost:8000/docs"
echo ""
echo "🏹 Тәңірі жарылқасын!"
echo "================================================================================"
