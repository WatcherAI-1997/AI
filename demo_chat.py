                    print("─"*80 + "\n")

                    messages = [{"role": "user", "content": question}]
                    result = model.generate(
                        messages=messages,
                        base_model_fn=mock_base_model,
                        temperature=0.7
                    )

                    print(f"💬 ОТВЕТ:\n")
                    print(result['response'])
                    print()

                    # Метаданные
                    if result['enhanced']:
                        print(f"📊 RAG: ✅ Обогащен ({result['metadata']['context_length']} символов)")
