            for num, question, desc in questions:
                if choice == num and num not in ["9", "0"]:
                    print("\n" + "="*80)
                    print(f"❓ ВОПРОС: {question}")
                    print("="*80 + "\n")
                    print("💭 Тамерлан думает...\n")

                    messages = [{"role": "user", "content": question}]
                    result = model.generate(
                        messages=messages,
                        base_model_fn=mock_base_model,
                        temperature=0.7
                    )

                    # Метаданные
                    print("─"*80)
                    print("📊 МЕТАДАННЫЕ:")
                    print(f"   • RAG обогащение: {'✅ ДА' if result['enhanced'] else '❌ НЕТ'}")

                    if result['enhanced']:
                        print(f"   • Контекст: {result['metadata']['context_length']} символов")
                        print(f"   • Релевантность: {result['metadata']['max_relevance']:.2f}")

                        if result['metadata']['categories']:
                            cats = ', '.join(result['metadata']['categories'])
                            print(f"   • Категории: {cats}")

                    print("─"*80 + "\n")

                    # Ответ
                    print("💬 ОТВЕТ ТАМЕРЛАНА:\n")
                    print(result['response'])
                    print("\n" + "="*80 + "\n")

                    found = True
                    break

            if not found:
                print("\n❌ Неверный номер. Выберите от 0 до 9.\n")

