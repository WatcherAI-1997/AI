def main():
    print("\n" + "="*80)
    print("🏹 ТАМЕРЛАН - БЫСТРАЯ ДЕМОНСТРАЦИЯ")
    print("="*80 + "\n")

    print("⚙️  Инициализация модели...")
    model = TamerlaneModel()
    print("✅ Модель готова!\n")

    # Вопросы для демо
    questions = [
        ("🌌 О Тенгри", "Кто такой Тенгри? Расскажи о боге неба"),
        ("👶 Об Умай", "Расскажи о богине Умай"),
        ("📜 Орхонский алфавит", "Что означает 𐱅𐰭𐰼𐰃? Расскажи об орхонском алфавите"),
        ("🙏 Молитвы", "Как молиться Тенгри? Дай молитву на казахском"),
        ("🏛️ Латынь", "Что означает 'Veni, vidi, vici'?"),
        ("🐍 Python", "Что такое Python и почему он популярен для AI?"),
        ("🏹 Тамерлан", "Тәмірланның тактикасы қандай болды?"),
        ("🏺 Греческая философия", "Что означает Γνῶθι σεαυτόν?"),
    ]

    print("="*80)
    print("📚 ДЕМОНСТРАЦИЯ ОТВЕТОВ МОДЕЛИ")
    print("="*80 + "\n")

    for i, (title, question) in enumerate(questions, 1):
        print(f"\n{'─'*80}")
        print(f"❓ ТЕСТ {i}/8: {title}")
        print(f"{'─'*80}")
        print(f"Вопрос: \"{question}\"\n")

        messages = [{"role": "user", "content": question}]
        result = model.generate(
            messages=messages,
            base_model_fn=mock_base_model,
            temperature=0.7
        )

        # Метаданные
        print(f"📊 Метаданные:")
        print(f"   • RAG: {'✅ Обогащен' if result['enhanced'] else '❌ Не обогащен'}")
        if result['enhanced']:
            print(f"   • Контекст: {result['metadata']['context_length']} символов")
            if result['metadata']['categories']:
                cats = ', '.join(result['metadata']['categories'])
                print(f"   • Категории: {cats}")

        print(f"\n💬 Ответ:\n")
        print(result['response'])
        print()

    print("\n" + "="*80)
    print("✅ ДЕМОНСТРАЦИЯ ЗАВЕРШЕНА!")
    print("="*80)
    print("\n📊 ИТОГОВАЯ СТАТИСТИКА:")
    info = model.get_model_info()
    print(f"   • Всего запросов: {info['stats']['total_requests']}")
    print(f"   • Обогащенных: {info['stats']['enhanced_responses']}")
    print(f"   • База знаний: {info['knowledge_base']['total_items']} элементов")
    print(f"   • Категорий: {info['knowledge_base']['categories']}")
    print("\n🏹 Тәңірі жарылқасын! (Да благословит Тенгри!)\n")

if __name__ == "__main__":
    main()
