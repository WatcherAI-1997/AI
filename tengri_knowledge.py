    def search_by_topic(self, topic: str) -> List[Dict]:
        """Поиск по теме"""
        results = []
        query_lower = topic.lower()

        for category, items in self.knowledge.items():
            if isinstance(items, list):
                for item in items:
                    # Поиск в разных полях
                    searchable_text = str(item).lower()
                    if query_lower in searchable_text:
                        results.append({
                            'category': category,
                            'item': item
                        })

        return results

    def get_stats(self) -> Dict:
        """Статистика"""
        total = sum(len(v) if isinstance(v, list) else 1 for v in self.knowledge.values())
        return {
            'categories': len(self.knowledge),
            'total_items': total,
            'main_topics': list(self.knowledge.keys())
        }


