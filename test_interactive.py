def mock_base_model(messages, temperature, max_tokens):
    """
    Мок-функция, которая демонстрирует, как модель обогащает ответы.
    В реальности здесь будет вызов к Anthropic Claude, Google Gemini, или другой модели.
    """
    # Получаем последнее сообщение пользователя
    user_message = ""
    system_message = ""

    for msg in messages:
        if msg['role'] == 'user':
            user_message = msg['content']
        elif msg['role'] == 'system':
            system_message = msg['content']

    # Проверяем, есть ли контекст
    has_context = "[КОНТЕКСТ ИЗ БАЗЫ ЗНАНИЙ" in system_message

    # Симулируем ответ с использованием контекста
    if has_context:
        # Извлекаем часть контекста для демонстрации
        context_start = system_message.find("[КОНТЕКСТ ИЗ БАЗЫ ЗНАНИЙ")
        context_end = system_message.find("[КОНЕЦ КОНТЕКСТА]")

        if context_start != -1 and context_end != -1:
            context_snippet = system_message[context_start:context_start+500]

            response = f"""Отвечаю на ваш вопрос, используя знания из моей базы данных:

"{user_message}"

[Здесь модель использовала контекст из базы знаний для формирования ответа]

Контекст включает информацию о:
{context_snippet[:200]}...

[В реальной версии с Claude/Gemini здесь будет полный развернутый ответ,
использующий всю информацию из контекста]
"""
            return response

    return f"""Отвечаю на: "{user_message}"

[Ответ без специального контекста - общие знания базовой модели]
"""


def print_section(title, char="="):
    """Печать красивой секции"""
    print(f"\n{char*80}")
    print(f"  {title}")
    print(f"{char*80}\n")


def test_query(model, query, description):
    """Тестирует один запрос"""
    print(f"\n{'─'*80}")
    print(f"📝 ТЕСТ: {description}")
    print(f"{'─'*80}")
    print(f"❓ Вопрос: \"{query}\"\n")

    messages = [{"role": "user", "content": query}]

    # Генерируем ответ
    result = model.generate(
        messages=messages,
        base_model_fn=mock_base_model,
        temperature=0.7,
        max_tokens=4000
    )

    # Показываем метаданные
    print(f"📊 МЕТАДАННЫЕ:")
    print(f"  • Обогащен контекстом: {'✅ ДА' if result['enhanced'] else '❌ НЕТ'}")
    print(f"  • Длина контекста: {result['metadata']['context_length']} символов")
    print(f"  • Язык запроса: {result['metadata']['detected_language']}")
    if result['metadata']['categories']:
        print(f"  • Категории: {', '.join(result['metadata']['categories'])}")

    # Показываем ответ
    print(f"\n💬 ОТВЕТ МОДЕЛИ:")
    print(f"{'─'*80}")
    print(result['response'])
    print(f"{'─'*80}")

    return result


